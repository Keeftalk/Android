package com.keeftalk.chat.data.remote

import com.keeftalk.chat.domain.model.UserChatSettings
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.*

@Serializable
data class UserChatSettingsDto(
    @SerialName("user_id") val userId: String,
    val theme: String = "SYSTEM",
    @SerialName("wallpaper_type") val wallpaperType: String = "COLOR",
    @SerialName("wallpaper_reference") val wallpaperReference: String = "#F0F2F5",
    @SerialName("bubble_style") val bubbleStyle: String = "MODERN",
    @SerialName("bubble_radius") val bubbleRadius: Int = 16,
    @SerialName("chat_density") val chatDensity: String = "COMFORTABLE",
    @SerialName("animations_enabled") val animationsEnabled: Boolean = true,
    @SerialName("emoji_size") val emojiSize: Int = 24,
    @SerialName("font_size") val fontSize: Int = 16,
    @SerialName("font_scale") val fontScale: Float = 1.0f,
    @SerialName("bold_text") val boldText: Boolean = false,
    @SerialName("high_contrast") val highContrast: Boolean = false,
    @SerialName("reduced_motion") val reducedMotion: Boolean = false,
    @SerialName("link_preview_size") val linkPreviewSize: String = "NORMAL",
    @SerialName("auto_download_mobile") val autoDownloadMobile: List<String> = listOf("PHOTO"),
    @SerialName("auto_download_wifi") val autoDownloadWifi: List<String> = listOf("PHOTO", "VIDEO", "AUDIO", "DOCUMENT"),
    @SerialName("auto_download_roaming") val autoDownloadRoaming: List<String> = emptyList(),
    @SerialName("upload_photo_quality") val uploadPhotoQuality: String = "HIGH",
    @SerialName("upload_video_quality") val uploadVideoQuality: String = "STANDARD",
    @SerialName("autoplay_gifs") val autoplayGifs: Boolean = true,
    @SerialName("autoplay_videos") val autoplayVideos: Boolean = true,
    @SerialName("autoplay_voice_notes") val autoplayVoiceNotes: Boolean = true,
    @SerialName("save_to_gallery") val saveToGallery: Boolean = false,
    @SerialName("enter_key_behavior") val enterKeyBehavior: String = "SEND",
    @SerialName("swipe_left_action") val swipeLeftAction: String = "ARCHIVE",
    @SerialName("swipe_right_action") val swipeRightAction: String = "REPLY",
    @SerialName("double_tap_action") val doubleTapAction: String = "REACT",
    @SerialName("default_reaction") val defaultReaction: String = "❤️",
    @SerialName("link_previews_enabled") val linkPreviewsEnabled: Boolean = true,
    @SerialName("auto_translate_mode") val autoTranslateMode: String = "DISABLED",
    @SerialName("auto_translate_language") val autoTranslateLanguage: String = "en"
) {
    fun toDomain() = UserChatSettings(
        userId = userId,
        theme = theme,
        wallpaperType = wallpaperType,
        wallpaperReference = wallpaperReference,
        bubbleStyle = bubbleStyle,
        bubbleRadius = bubbleRadius,
        chatDensity = chatDensity,
        animationsEnabled = animationsEnabled,
        emojiSize = emojiSize,
        fontSize = fontSize,
        fontScale = fontScale,
        boldText = boldText,
        highContrast = highContrast,
        reducedMotion = reducedMotion,
        linkPreviewSize = linkPreviewSize,
        autoDownloadMobile = autoDownloadMobile,
        autoDownloadWifi = autoDownloadWifi,
        autoDownloadRoaming = autoDownloadRoaming,
        uploadPhotoQuality = uploadPhotoQuality,
        uploadVideoQuality = uploadVideoQuality,
        autoplayGifs = autoplayGifs,
        autoplayVideos = autoplayVideos,
        autoplayVoiceNotes = autoplayVoiceNotes,
        saveToGallery = saveToGallery,
        enterKeyBehavior = enterKeyBehavior,
        swipeLeftAction = swipeLeftAction,
        swipeRightAction = swipeRightAction,
        doubleTapAction = doubleTapAction,
        defaultReaction = defaultReaction,
        linkPreviewsEnabled = linkPreviewsEnabled,
        autoTranslateMode = autoTranslateMode,
        autoTranslateLanguage = autoTranslateLanguage
    )

    companion object {
        fun fromDomain(settings: UserChatSettings) = UserChatSettingsDto(
            userId = settings.userId,
            theme = settings.theme,
            wallpaperType = settings.wallpaperType,
            wallpaperReference = settings.wallpaperReference,
            bubbleStyle = settings.bubbleStyle,
            bubbleRadius = settings.bubbleRadius,
            chatDensity = settings.chatDensity,
            animationsEnabled = settings.animationsEnabled,
            emojiSize = settings.emojiSize,
            fontSize = settings.fontSize,
            fontScale = settings.fontScale,
            boldText = settings.boldText,
            highContrast = settings.highContrast,
            reducedMotion = settings.reducedMotion,
            linkPreviewSize = settings.linkPreviewSize,
            autoDownloadMobile = settings.autoDownloadMobile,
            autoDownloadWifi = settings.autoDownloadWifi,
            autoDownloadRoaming = settings.autoDownloadRoaming,
            uploadPhotoQuality = settings.uploadPhotoQuality,
            uploadVideoQuality = settings.uploadVideoQuality,
            autoplayGifs = settings.autoplayGifs,
            autoplayVideos = settings.autoplayVideos,
            autoplayVoiceNotes = settings.autoplayVoiceNotes,
            saveToGallery = settings.saveToGallery,
            enterKeyBehavior = settings.enterKeyBehavior,
            swipeLeftAction = settings.swipeLeftAction,
            swipeRightAction = settings.swipeRightAction,
            doubleTapAction = settings.doubleTapAction,
            defaultReaction = settings.defaultReaction,
            linkPreviewsEnabled = settings.linkPreviewsEnabled,
            autoTranslateMode = settings.autoTranslateMode,
            autoTranslateLanguage = settings.autoTranslateLanguage
        )
    }
}
