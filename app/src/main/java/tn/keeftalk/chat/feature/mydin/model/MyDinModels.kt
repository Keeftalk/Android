fun parseTajweedToAnnotatedString(
    rawTajweed: String,
    isDark: Boolean = false
): AnnotatedString {
    val hamColor = if (isDark) Color(0xFF7E8C89) else Color(0xFF9AA6A3)
    val maddNColor = if (isDark) Color(0xFF6FA8FF) else Color(0xFF2A6FDB)
    val maddOColor = if (isDark) Color(0xFF8F8CFF) else Color(0xFF1F4FB0)
    val maddJColor = if (isDark) Color(0xFFB39DFF) else Color(0xFF0B2E8C)
    val ikhfaColor = if (isDark) Color(0xFFCE93D8) else Color(0xFF8E24AA)
    val ikhfaShColor = if (isDark) Color(0xFFF48FB1) else Color(0xFFC2185B)
    val idghamColor = if (isDark) Color(0xFF81C784) else Color(0xFF2E7D32)
    val idghamShColor = if (isDark) Color(0xFFAED581) else Color(0xFF558B2F)
    val iqlabColor = if (isDark) Color(0xFF4DD0E1) else Color(0xFF00838F)
    val ghunnahColor = if (isDark) Color(0xFFFFB74D) else Color(0xFFEF6C00)
    val qlqColor = if (isDark) Color(0xFFEF9A9A) else Color(0xFFC62828)
    val silentColor = if (isDark) Color(0xFF9E9E9E) else Color(0xFF757575)
    val lamShamsColor = if (isDark) Color(0xFF2EE5E5) else Color(0xFF00A3A3)
    val saktColor = if (isDark) Color(0xFFFF7043) else Color(0xFFD84315)

    val regex = Regex("\\[([a-z])(?::(\\d+))?\\[([^]]*)\\]\\]?")

    return buildAnnotatedString {
        var lastIndex = 0
        for (match in regex.findAll(rawTajweed)) {
            if (match.range.first > lastIndex) {
                append(rawTajweed.substring(lastIndex, match.range.first))
            }
            val ruleCode = match.groupValues[1]
            val content = match.groupValues[3]

            val textColor = when (ruleCode) {
                "h" -> hamColor
                "n" -> maddNColor
                "o" -> maddOColor
                "j" -> maddJColor
                "f", "k" -> ikhfaColor
                "w" -> ikhfaShColor
                "g", "u" -> idghamColor
                "b", "l" -> idghamShColor
                "i" -> iqlabColor
                "m" -> ghunnahColor
                "q" -> qlqColor
                "c" -> silentColor
                "p" -> lamShamsColor
                "s" -> saktColor
                else -> Color.Unspecified
            }

            if (textColor != Color.Unspecified) {
                pushStyle(SpanStyle(color = textColor, fontWeight = FontWeight.SemiBold))
                append(content)
                pop()
            } else {
                append(content)
            }
            lastIndex = match.range.last + 1
        }
        if (lastIndex < rawTajweed.length) {
            append(rawTajweed.substring(lastIndex))
        }
    }
}
